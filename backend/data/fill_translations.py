#  Patch the CSV 
import csv, shutil
from datetime import datetime

CSV_FILE = "medical_corpus.csv"
BACKUP   = f"medical_corpus_backup_{datetime.now().strftime('%Y%m%d_%H%M%S')}.csv"

# Step 1: Backup
shutil.copy(CSV_FILE, BACKUP)
print(f" Backup created: {BACKUP}")

# Step 2: Read all rows
with open(CSV_FILE, newline="", encoding="utf-8") as f:
    reader = csv.DictReader(f)
    fieldnames = reader.fieldnames
    rows = list(reader)

# Step 3: Patch
patched = 0
skipped = 0
for row in rows:
    sid = str(row["sentence_id"])
    if sid in TRANSLATIONS:
        if not str(row.get("sesotho_text") or "").strip():
            row["sesotho_text"] = TRANSLATIONS[sid]
            patched += 1
        else:
            skipped += 1  # already had a translation, left untouched

# Step 4: Write back
with open(CSV_FILE, "w", newline="", encoding="utf-8") as f:
    writer = csv.DictWriter(f, fieldnames=fieldnames)
    writer.writeheader()
    writer.writerows(rows)

print(f" Patched : {patched} rows")
print(f"  Skipped : {skipped} rows (already had translations)")
print(f" Saved   : {CSV_FILE}")

